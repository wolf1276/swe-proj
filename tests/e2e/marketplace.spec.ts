import { test, expect, type Page, type BrowserContext } from "@playwright/test";
import { randomUUID } from "node:crypto";
import { readdir, readFile } from "node:fs/promises";
import AxeBuilder from "@axe-core/playwright";

const password = "local-seed-pass-1234";
async function login(page: Page, email: string) {
  await page.goto("/sign-in");
  await page.getByLabel("Campus email", { exact: true }).fill(email);
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page).toHaveURL(/\/listings$/);
}
async function createItem(page: Page, title: string, donation = false) {
  await page.goto("/listings/new");
  await page.getByLabel("Title", { exact: true }).fill(title);
  await page.getByLabel("Description", { exact: true }).fill("A reusable campus item for testing.");
  await page.getByLabel("Category", { exact: true }).selectOption({ label: "Textbooks" });
  await page.getByLabel("Condition", { exact: true }).selectOption("good");
  if (donation) await page.getByRole("radio", { name: "Donation", exact: true }).check();
  else await page.getByLabel("Price (rupees)", { exact: true }).fill("250");
  await page.getByRole("button", { name: "Create listing", exact: true }).click();
  await expect(page).toHaveURL(/\/listings\/[\da-f-]+$/);
  await expect(page.getByRole("heading", { level: 1 })).toHaveText(title);
  return new URL(page.url()).pathname;
}
async function api(context: BrowserContext, path: string, method = "GET", data?: unknown) {
  return context.request.fetch(path, { method, headers: { origin: "https://localhost:3100" }, ...(data !== undefined ? { data } : {}) });
}

test("TC-S01/S02 real registration, local mail verification, replay and expired proof", async ({ page, context, browser }) => {
  const email = `e2e-${randomUUID()}@campus.example`;
  await page.goto("/sign-up");
  await page.getByLabel("Display name").fill("Verified E2E Student");
  await page.getByLabel("Campus email", { exact: true }).fill(`outside-${randomUUID()}@outside.example`);
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Sign up", exact: true }).click();
  await expect(page.getByRole("main").getByRole("alert")).toContainText("approved campus email");
  await page.getByLabel("Campus email", { exact: true }).fill(email);
  await page.getByRole("button", { name: "Sign up", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Check your email" })).toBeVisible();
  expect((await api(context, "/api/listings")).status()).toBe(401);
  const denied = await context.request.post("/api/auth/sign-in/email", { data: { email, password }, headers: { origin: "https://localhost:3100" } });
  expect(denied.status()).toBe(403);
  let link = "";
  await expect.poll(async () => {
    const files = (await readdir(".mail-e2e")).filter(f => f.endsWith(".json")).sort().reverse();
    const items = await Promise.all(files.slice(0, 100).map(async file => JSON.parse(await readFile(`.mail-e2e/${file}`, "utf8"))));
    const mail = items.find((m: { to: string }) => m.to === email);
    link = mail?.text.match(/https:\/\/localhost:3100\/api\/auth\/verify-email\?[^\s]+/)?.[0] ?? "";
    return link;
  }).not.toBe("");
  await page.goto(link);
  await expect(page).toHaveURL(/\/(verify-email|listings)$/);
  expect((await (await api(context, "/api/me")).json()).user.emailVerified).toBe(true);
  await page.goto("/listings");
  await expect(page.getByRole("heading", { name: "Browse listings" })).toBeVisible();
  // Reusing proof in a new browser must not establish another session.
  const fresh = await browser.newContext({ baseURL: "https://localhost:3100", ignoreHTTPSErrors: true });
  await fresh.request.get(link);
  expect((await api(fresh, "/api/listings")).status()).toBe(401);
  const invalid = await fresh.newPage();
  await invalid.goto("/api/auth/verify-email?token=invalid&callbackURL=/verify-email");
  await expect(invalid.getByText("This verification link is invalid or has expired.")).toBeVisible();
  const { signJWT } = await import("better-auth/crypto");
  const expired = await signJWT({ email }, "e2e-local-only-secret-0123456789abcdef0123456789", -60);
  await invalid.goto(`/api/auth/verify-email?token=${expired}&callbackURL=/verify-email`);
  await expect(invalid.getByText("This verification link is invalid or has expired.")).toBeVisible();
  await fresh.close();
  await page.getByRole("button", { name: "Sign out" }).click();
  await expect(page).toHaveURL(/\/sign-in$/);
  await page.goBack();
  await expect(page).toHaveURL(/\/sign-in$/);
  await expect(page.getByRole("heading", { name: "Browse listings" })).not.toBeVisible();
  await page.goto("/listings");
  await expect(page).toHaveURL(/\/sign-in$/);
});

