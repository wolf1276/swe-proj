test("mobile layout, keyboard access, recovery and API security", async ({ page, context }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await login(page, "a.student@campus.example");
  await expect(page.getByRole("heading", { name: "Browse listings" })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("browse-mobile.png"), fullPage: true });
  const accessibility = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
  expect(accessibility.violations).toEqual([]);
  await page.getByLabel("Search", { exact: true }).fill("unlikely-empty-result-" + randomUUID());
  await page.getByLabel("Search", { exact: true }).press("Enter");
  await expect(page.getByText("No listings match", { exact: true })).toBeVisible();
  await page.goto("/listings/new");
  await page.getByRole("button", { name: "Create listing", exact: true }).click();
  await expect(page.getByRole("main").getByRole("alert")).toContainText("Title must be at least 3 characters");
  await page.getByLabel("Title", { exact: true }).fill("Preserved on network failure");
  await page.getByLabel("Price (rupees)", { exact: true }).fill("50");
  await page.route("**/api/listings", route => route.abort());
  await page.getByRole("button", { name: "Create listing", exact: true }).click();
  await expect(page.getByRole("main").getByRole("alert")).toContainText("Network error");
  await expect(page.getByLabel("Title", { exact: true })).toHaveValue("Preserved on network failure");
  const csrf = await context.request.post("/api/listings", { headers: { origin: "https://attacker.example" }, data: {} });
  expect(csrf.status()).toBe(403);
  expect((await api(context, "/api/dev/mailbox")).status()).toBe(404);
  expect((await api(context, "/api/auth/admin/set-role", "POST", { userId: "irrelevant", role: "admin" })).status()).toBe(404);
  expect((await api(context, "/api/listings?minPriceMinor=100&maxPriceMinor=0")).status()).toBe(400);
});

 test("student eligibility and operator admin privilege remain independent", async ({ page, context }) => {
   await login(page, "operator@staff.example");
   await expect(page.getByRole("heading", { name: "Campus access required" })).toBeVisible();
   expect((await api(context, "/api/listings")).status()).toBe(403);
   expect((await api(context, "/api/admin/users")).status()).toBe(200);
   await page.goto("/admin/users");
   await page.getByLabel("Find a user").fill("b.student@campus.example");
   await page.getByRole("button", { name: "Search users" }).click();
   await expect(page.getByRole("status")).toContainText("1 users found");
   await page.goto("/listings/new");
   await expect(page.getByRole("heading", { name: "Campus access required" })).toBeVisible();
   const reports = await (await api(context, "/api/admin/reports?state=actioned")).json();
   const reviewedId = reports.items[0].listing.id;
   await page.goto(`/listings/${reviewedId}`);
   await expect(page.getByRole("heading", { name: "Campus access required" })).toBeVisible();
   await page.goto(`/listings/${reviewedId}/edit`);
   await expect(page.getByRole("heading", { name: "Campus access required" })).toBeVisible();
   const forged = await api(context, "/api/auth/sign-up/email", "POST", { email: `privilege-${randomUUID()}@campus.example`, password, name: "Forged", role: "admin", emailVerified: true });
   expect(forged.status()).toBe(400);
   const outside = await api(context, "/api/auth/sign-up/email", "POST", { email: `forged-${randomUUID()}@outside.example`, password, name: "Ineligible" });
   expect([400, 403, 422]).toContain(outside.status());
 });
